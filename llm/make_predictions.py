"""Generate llm/STAGE3_PREDICTIONS.md and results/llm/stage2/stage3_predictions.json from the Stage 2 summaries
(no hand-copied numbers). Run before any Stage 3 live call; commit the outputs.   python llm/make_predictions.py"""
import json, os
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = pd.read_csv(os.path.join(ROOT, "results/llm/stage2/summary_stage3.csv"))
# (id, endpoint, framing, rho, primary measures, what it tests)
POINTS = [
    ("P1", "qwen-122b", "neutral", 0.25, ["abs_m", "persistence"],
     "ordering despite rival ties (summation α≈0, rivals mildly attract, inertia γ≈2.2)"),
    ("P2", "qwen-9b", "political", 0.5, ["m", "persistence"],
     "social amplification of the content field with half the ties rival"),
    ("P3", "llama-70b", "political", 0.25, ["abs_m", "persistence"],
     "stubbornness freezing (γ≈5.6, persistence vs the Ising reading) with social alignment on top of the field (|m| vs both controls)"),
    ("P4", "nemo-12b", "workplace", 0.25, ["m", "persistence"],
     "a weak coupler (β≈0.2) amplifying a content field into near-consensus"),
]
CAL = ("P5 (optional calibration)", "gpt6-luna", "neutral", 0.0, ["abs_m", "persistence"],
       "the most Ising-like endpoint: surrogate and Ising reading agree")
LAB = {"abs_m": "|m|", "m": "m (toward P)", "persistence": "persistence", "excess_unsat": "excess unsatisfied ties",
       "flip_rate": "flip rate", "abs_q": "|q|"}
PRICE_PER_1K = {"llama-70b": 0.110, "qwen-122b": 0.044, "qwen-9b": 0.017, "nemo-12b": 0.002, "gpt6-luna": 0.020}


def row(pop, fr, rho, mode, graph="rrg"):
    q = S[(S["pop"] == pop) & (S.framing == fr) & (S.rho == rho) & (S.graph == graph) & (S.eps == 0) & (S["mode"] == mode)]
    return q.iloc[0]


def fmt(r, m):
    return f"{r[m]:.2f} [{r[m + '_mean5_lo']:.2f}, {r[m + '_mean5_hi']:.2f}]"


out, lines = {}, []
lines += ["# Stage 3 predictions (written before any live-network call)", "",
          "Generated by `llm/make_predictions.py` from `results/llm/stage2/summary_stage3.csv` (Stage 2 surrogate "
          "simulations, `llm/stage2.py`). Committed before any Stage 3 API call. Claims concern **these models at these "
          "pinned endpoints**, not LLMs in general.", "",
          "## Stage 3 protocol (the surrogate simulations use exactly this)", "",
          "- **Network:** N = 100 agents on a random-regular graph with degree 4. Every agent has exactly 4 contacts, inside "
          "the fitted k ≤ 6 range; ER c = 4 would put ≈ 11% of agents beyond it.",
          "- **Ties:** each tie is rival with probability ρ, and both ends perceive it the same way (ε = 0).",
          "- **Replication:** 5 independent graphs per point, two replicas per graph, each replica starting from an "
          "independent 50/50 random configuration.",
          "- **Updates:** asynchronous random-sequential, 10 warm-up sweeps then 10 measured sweeps (2,000 updates per "
          "replica).",
          "- **Each update is one API call** to the pinned Stage 1 endpoint, using the Stage 1 template for the point's "
          "framing (instruction v2). The prompt gives the agent's own current position and its 4 contacts, each on its own "
          "line, in random order.",
          "  - **Per-call randomisation:** a fresh random letter mapping (which content is A) and a fresh random option "
          "order (Amendment 3d). In neutral framing the positions are relabelled per call.",
          "  - **Decision:** sampled locally from the returned first-token logprobs at T = 1, renormalised over {A, B}. A "
          "call with leak > 5% is repeated once; if it leaks again, the agent keeps its position (logged).",
          "- **Measures** are identical to `llm/surrogate.py`, time-averaged over the 10 measured sweeps:",
          "  - |m| and signed m (+ = position P);",
          "  - persistence: overlap with the agent's own configuration at the end of warm-up;",
          "  - flip rate;",
          "  - excess unsatisfied ties: the fraction of directed ties that are unsatisfied, minus the frustration floor for "
          "the same graph family and ρ (0 at ρ = 0; 0.146–0.153 at ρ ≥ 0.25);",
          "  - replica overlap |q|.",
          "", "## Predictions", "",
          "Entries: median run, then [90% interval of the **mean of 5 graphs**]. Each interval combines parameter "
          "uncertainty (cluster-bootstrap draws), graph disorder and dynamical noise (40 simulated runs per condition).",
          "- **Fitted surrogate:** the A3 logit with k^-α scaling, plus a first-contact voter step where it won held-out "
          "(not in these four points), inertia γ, and the content field h_C. Letter and order fields are randomised per "
          "call.",
          "- **Fields-only control:** the same γ and fields, but no social coupling.",
          "- **Ising reading:** the Stage 1 additive β only.",
          ""]
pred = []
for pid, pop, fr, rho, prim, what in POINTS + [CAL]:
    F, Fo, I = row(pop, fr, rho, "fitted"), row(pop, fr, rho, "fields_only"), row(pop, fr, rho, "ising")
    calls = 5 * 2 * 100 * 20
    lines += [f"### {pid}: {pop}, {fr} framing, ρ = {rho}", "", f"Tests: {what}. Primary measures: "
              + ", ".join(LAB[m] for m in prim) + f". Surrogate regime: **{F.regime}**.", "",
              "| measure | fitted surrogate | fields-only control | Ising reading |", "|---|---|---|---|"]
    for m in ["abs_m", "m", "persistence", "excess_unsat", "flip_rate", "abs_q"]:
        star = " **(primary)**" if m in prim else ""
        lines.append(f"| {LAB[m]}{star} | {fmt(F, m)} | {fmt(Fo, m)} | {fmt(I, m)} |")
    lines += ["", f"Calls: {calls:,} (≈ ${calls / 1000 * PRICE_PER_1K[pop]:.2f} at Stage 1 per-call cost).", ""]
    pred.append({"id": pid, "endpoint": pop, "framing": fr, "rho": rho, "graph": "rrg", "N": 100, "primary": prim,
                 **{f"{mode}_{m}_{k}": float(r[m + suf]) for mode, r in (("fitted", F), ("fields_only", Fo), ("ising", I))
                    for m in ["abs_m", "m", "persistence", "excess_unsat", "flip_rate", "abs_q"]
                    for k, suf in (("median", ""), ("mean5_lo", "_mean5_lo"), ("mean5_hi", "_mean5_hi"))}})
lines += ["## Pre-stated evaluation", "",
          "For each point, compute the observed mean over the 5 graphs of each measure (replicas averaged within each "
          "graph).",
          "- **Surrogate passes a measure** if the observed mean lies inside the fitted surrogate's 90% "
          "mean-of-5 interval.",
          "- **The point is discriminating** if the observed primary measures fall outside the control intervals "
          "the surrogate is meant to beat:",
          "  - P1, P2, P4: both primary measures outside both the Ising-reading and the fields-only intervals.",
          "  - P3: |m| outside both control intervals; persistence outside the Ising interval (the fields-only control "
          "predicts the same freezing, so persistence cannot separate it).",
          "- **Overall:** the surrogate is supported if it passes both primary measures at ≥ 3 of P1–P4. The naive Ising "
          "reading is rejected at a point if its interval excludes the observed primary measure. P5 is a calibration "
          "and does not count toward the verdict.",
          "- **Operating characteristic of this rule:** if the surrogate were exactly right and the two primary "
          "measures independent, each lies inside its 90% interval with probability 0.9. Both pass at a point with "
          "≈ 0.81, and ≥ 3 of 4 points pass with ≈ 0.83. A correct surrogate is therefore declared 'not supported' "
          "≈ 17% of the time.",
          "- **Reporting:** all measures are reported at every point, whatever the outcome. No re-fitting and no "
          "change of points after seeing Stage 3 data.", "",
          "## Caveats", "",
          "- **Finite-time, finite-size predictions:** N = 100, 20 sweeps. The long-run behaviour is in "
          "`results/llm/stage2/summary_fss.csv`.",
          "  - In neutral framing, Qwen-122B keeps order up to N = 1600 at ρ ≤ 0.25, and Llama-70B coarsens slowly "
          "(unclear).",
          "  - Political and workplace 'order' is field-driven: there is a content field, so it is not a phase "
          "transition.",
          "- **The surrogates are fitted on single-shot prompts.** Stage 3 tests whether the network dynamics follow from "
          "the single-shot response function; any memory or history effects in live agents are what Stage 3 can "
          "reveal.",
          "- **These four points use only confirmatory endpoints** (they passed both the comprehension check and the "
          "noise gate). The Gemma endpoints await the local bf16 replication (Amendment 4).",
          "- **ER c = 4 predictions are in the summary file as secondary.** At Stage 3 scale they differ from the "
          "random-regular ones by ≤ 0.16 in |m|.",
          f"- **Cost:** P1–P4 total ≈ ${sum(5*2*100*20/1000*PRICE_PER_1K[p[1]] for p in POINTS):.2f} at Stage 1 "
          "per-call cost (≈ $5 with a 50% margin). P5 is a sampling endpoint (one sampled reply per update) and "
          "adds ≈ $0.40."]
MD = os.path.join(ROOT, "llm", "STAGE3_PREDICTIONS.md")
ADD = "## Pre-data addendum"           # appended by hand before any live call; preserved on regeneration
tail = ""
if os.path.exists(MD) and ADD in open(MD).read():
    tail = "\n" + open(MD).read()[open(MD).read().index(ADD):]
open(MD, "w").write("\n".join(lines) + "\n" + tail)
json.dump(pred, open(os.path.join(ROOT, "results/llm/stage2/stage3_predictions.json"), "w"), indent=1)
# addendum (b): no-contacts control arms for P2 and P4. With no contacts the surrogate update is
# eta = gamma*s + h_C + h_L*L + h_O*O, which is exactly the fields-only control, so its rows are the prediction.
nc = [{"id": p["id"] + "-nc", "endpoint": p["endpoint"], "framing": p["framing"], "rho": p["rho"], "graph": "rrg", "N": 100,
       "contacts_shown": False, "primary": p["primary"], "extrapolation": "k = 0 is outside the fitted k = 1..6 range",
       **{k.replace("fields_only_", "predicted_"): v for k, v in p.items() if k.startswith("fields_only_")}}
      for p in pred if p["id"] in ("P2", "P4")]
json.dump(nc, open(os.path.join(ROOT, "results/llm/stage2/stage3_predictions_nocontacts.json"), "w"), indent=1)
print("\n".join(lines))
